// True when a record has a verified leading-brand reference price
export function hasBrandReference(medicine) {
  return medicine.brandReferencePrice != null
}

// Helper: savings for one pack, or null if no verified brand reference exists yet
export function getSavings(medicine) {
  if (!hasBrandReference(medicine)) return null
  const amount = medicine.brandReferencePrice - medicine.janAushadhiPrice
  const percent =
    medicine.brandReferencePrice > 0 ? (amount / medicine.brandReferencePrice) * 100 : 0
  return { amount, percent }
}

// Helper: case-insensitive search by medicine name, official generic name or
// reference brand name (so "Dolo 650" finds the Jan Aushadhi Paracetamol 650 mg)
export function searchMedicines(query) {
  const q = query.trim().toLowerCase()
  if (!q) return medicines
  return medicines.filter(
    (m) =>
      m.name.toLowerCase().includes(q) ||
      m.genericName.toLowerCase().includes(q) ||
      m.brandReference?.productName.toLowerCase().includes(q),
  )
}

// Helper: format a number as Indian Rupees, e.g. ₹1,234.50
export function formatINR(value) {
  return new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    maximumFractionDigits: 2,
  }).format(value)
}

// Helper: format an ISO date (YYYY-MM-DD) as e.g. 8 Oct 2026
export function formatDate(iso) {
  return new Date(`${iso}T00:00:00`).toLocaleDateString('en-IN', {
    day: 'numeric',
    month: 'short',
    year: 'numeric',
  })
}
