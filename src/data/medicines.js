// brand listing's composition must name the same single ingredient and the same
// strength as the PMBI record, in the same dosage form (e.g. a dispersible,
// chewable, combination or different-release brand is never used). When the PMBI
// product is gastro-resistant or modified-release, the brand listing must itself
// confirm that form (e.g. "tablet sr"); a listing that only says "tablets" is not
// accepted, unless the drug exists solely in that form. Records without a
// defensible brand reference are left out rather than shown without one.
//
// This data makes no claim that one product can replace another — that decision
// belongs to a doctor or pharmacist.

